// UnitTrainingCost 计算 before→after 的训练成本（索引先做边界校验，越界报错）。
func UnitTrainingCost(before, after int) (int, error) {
	if before < 1 || after > UnitExpTableLen {
		return 0, fmt.Errorf("%w: before=%d after=%d 超出 [1,%d]", ErrTrainingOutOfRange, before, after, UnitExpTableLen)
	}
	if after <= before {
		return 0, fmt.Errorf("%w: after=%d 必须大于 before=%d", ErrTrainingOutOfRange, after, before)
	}
	return unitExpTable[after-1] - unitExpTable[before-1], nil
}
